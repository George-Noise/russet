#!/usr/bin/env bash
# Delivery ritual in one command (owner request 2026-11-17 — AGENTS.md
# "Delivery ritual"): builds BOTH fixed-name artifacts from the current
# worktree, byte-compares all three copies (patched clean base <-> worktree
# <-> unpacked zip) and prints sizes + sha256 checksums.
#
# Usage: bash scripts/deliver.sh [base-ref] [out-dir]
#   base-ref  what the owner's local tree is right now (default: origin/master
#             — his latest pushed commit; pass the SHA stated by the previous
#             session if the sandbox has no origin/master)
#   out-dir   where the artifacts go (default: /tmp/russet-delivery)
#
# Exit 0 only when every byte-compare matched; any mismatch exits 1 and the
# artifacts in out-dir are NOT to be sent.
set -euo pipefail
cd "$(dirname "$0")/.."

BASE="${1:-origin/master}"
OUT="${2:-/tmp/russet-delivery}"
TMP="$(mktemp -d)"
STAGE="$TMP/stage"
# What is untracked NOW (before this script intent-adds anything): the cleanup
# resets ONLY these index entries (dropping the markers this script created).
# A blunt `git reset` here would also undo whatever the CALLER had already
# staged — e.g. a `git rm`'d file — and silently corrupt the next run (the
# index would list a file the worktree no longer has). Caught live 2026-11-17.
# The list goes to a FILE: a $(...) substitution would drop the NUL separators.
UNTRACKED_BEFORE="$TMP/untracked_before.list"
git ls-files --others --exclude-standard -z > "$UNTRACKED_BEFORE" 2>/dev/null || : > "$UNTRACKED_BEFORE"
cleanup() {
  xargs -0 -r git reset -q -- < "$UNTRACKED_BEFORE" 2>/dev/null || true
  rm -rf "$TMP"
}
trap cleanup EXIT

if git rev-parse --verify --quiet "$BASE^{commit}" > /dev/null; then
  BASE_SHA=$(git rev-parse --short "$BASE")
else
  echo "deliver.sh: base '$BASE' does not resolve" >&2
  exit 1
fi
rm -f "$OUT/russet.zip" "$OUT/russet.patch" && mkdir -p "$OUT"

# Stage the worktree exactly: with git — tracked + untracked-but-not-ignored
# files (gitignore keeps target/, .git, result* out AND the Python bytecode
# caches (__pycache__/, *.pyc — regenerated by every run of visual_driver.py,
# which imports mcp_smoke) — the owner caught mcp_smoke.cpython-312.pyc in
# BOTH artifacts 2026-11-18: the stage mirrors the ignore rules, so the
# exclusion lives in .gitignore, not here), intent-to-add first so
# NEW files enter the patch too; without git — plain tar with explicit
# excludes.
rm -rf "$STAGE" && mkdir -p "$STAGE/russet"
if git rev-parse --is-inside-work-tree > /dev/null 2>&1; then
  git ls-files --others --exclude-standard -z | xargs -0 -r git add -N --
  git ls-files --cached --others --exclude-standard -z | tar --null -T - -cf - | tar -xf - -C "$STAGE/russet"
else
  tar -cf - --exclude=.git --exclude=target --exclude=__pycache__ \
      --exclude='result*' --exclude='.env' . | tar -xf - -C "$STAGE/russet"
fi

# HARD guard on the bytecode caches (re-caught 2026-11-19: the v5 round
# CLAIMED the .gitignore entries in its Files list but they never landed in
# the owner's tree — the comment drifted, the leak reopened on the next
# import). The entries are in .gitignore NOW and visual_driver.py stops
# writing them; this guard fails the delivery regardless of any future
# drift. Both artifacts come from the stage (the patch from the intent-add
# index, the zip from the staged tree), so one check covers both.
if find "$STAGE" \( -name '__pycache__' -o -name '*.pyc' \) | grep -q .; then
  echo "deliver.sh: Python bytecode cache in the stage — delete it and fix .gitignore" >&2
  exit 1
fi

# 1. russet.zip
(cd "$STAGE" && zip -qr "$OUT/russet.zip" russet)

# 2. russet.patch (only with git — no git, no patch, zip is the sole artifact)
if git rev-parse --is-inside-work-tree > /dev/null 2>&1; then
  # --no-renames: a rename-form diff ("rename from/to" + a partial body) is
  # mis-applied by non-git patchers — one such apply left the rename SOURCE
  # (the old panels.rs) alive in the owner's commit 3be38d4 as a 504-line
  # dead orphan next to its split successors. Plain delete+add diffs apply
  # unambiguously everywhere. Caught live 2026-11-17.
  git diff --binary --no-renames "$BASE" > "$OUT/russet.patch"
else
  echo "deliver.sh: NO git here — russet.patch skipped, russet.zip is the only artifact" >&2
fi
# Patch-side half of the same guard (the stage check above sees the tree;
# the patch is a diff of the index — the ^diff header pattern avoids false
# positives on source comments mentioning "__pycache__", e.g. deliver.sh's).
if [ -f "$OUT/russet.patch" ] \
    && grep -qE '^diff --git a/.*(__pycache__|\.pyc)' "$OUT/russet.patch"; then
  echo "deliver.sh: Python bytecode cache in the patch — delete it and fix .gitignore" >&2
  exit 1
fi

# 3. Byte-compares (all must match).
if [ -f "$OUT/russet.patch" ]; then
  mkdir -p "$TMP/base"
  git archive "$BASE" | tar -xf - -C "$TMP/base"
  if [ -s "$OUT/russet.patch" ]; then
    git -C "$TMP/base" apply "$OUT/russet.patch"
  fi
  diff -r "$TMP/base" "$STAGE/russet" > /dev/null \
    || { echo "deliver.sh: MISMATCH patched-base <-> worktree" >&2; exit 1; }
  echo "byte-compare: patched $BASE_SHA <-> worktree — MATCH"
fi
mkdir -p "$TMP/unzip" && (cd "$TMP/unzip" && unzip -q "$OUT/russet.zip")
diff -r "$TMP/unzip/russet" "$STAGE/russet" > /dev/null \
  || { echo "deliver.sh: MISMATCH unpacked zip <-> worktree" >&2; exit 1; }
echo "byte-compare: unpacked zip <-> worktree — MATCH"

# 4. The hand-over numbers.
echo "deliver.sh: DELIVERY READY (base $BASE_SHA) — artifacts in $OUT"
ls -la "$OUT"
sha256sum "$OUT"/russet.zip "$OUT"/russet.patch 2>/dev/null || sha256sum "$OUT"/russet.zip
